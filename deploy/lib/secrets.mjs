// The secrets the pipeline makes itself, once, straight into SSM Parameter Store (SecureString). They are never
// printed, never written to a file, never passed on a command line, never in git: generated in this process, sent to
// SSM over TLS, forgotten. A parameter that exists is never read and never overwritten (rotation:
// docs/DEPLOY-AWS.md, "Rotating a secret").
import { generateKeyPairSync, randomBytes } from "node:crypto";
import { DescribeParametersCommand, GetParameterCommand, PutParameterCommand } from "@aws-sdk/client-ssm";
import { info } from "./log.mjs";

export const appPrefix = (env) => `/fenvix/${env}/github-app`;
export const cachePrefix = (env) => `/fenvix/${env}/cache`;

/** 32 random bytes as 64 hex characters (the format the services' minimum lengths expect). */
export const randomHex = () => randomBytes(32).toString("hex");

/** The generated secrets: name (under the App's prefix) and how each is made. */
export const GENERATED = [
  { name: "webhook-secret", make: randomHex, what: "the GitHub App's webhook secret (paste it on the App's page when you create the App)" },
  { name: "state-signing-key", make: randomHex, what: "signs the state of the install link" },
  { name: "runner-token", make: randomHex, what: "signs each runner machine's own summary credential" },
];

/** The cache signing key pair (per-job mode): RSA 3072; the private half signs per-job cache tokens. */
export function cacheKeyPair() {
  const { privateKey, publicKey } = generateKeyPairSync("rsa", { modulusLength: 3072 });
  return {
    privatePem: privateKey.export({ type: "pkcs8", format: "pem" }).toString(),
    publicDerBase64: publicKey.export({ type: "spki", format: "der" }).toString("base64"),
  };
}

export async function exists(ssm, name) {
  const r = await ssm.send(new DescribeParametersCommand({ ParameterFilters: [{ Key: "Name", Option: "Equals", Values: [name] }] }));
  return (r.Parameters ?? []).length > 0;
}

/** Creates the parameter if it does not exist. Never overwrites (Overwrite: false: a parallel run cannot either). */
export async function ensureSecret(ssm, name, make, description) {
  if (await exists(ssm, name)) { info(`${name}: present (kept)`); return "kept"; }
  try {
    await ssm.send(new PutParameterCommand({ Name: name, Type: "SecureString", Value: make(), Overwrite: false, Description: description, Tier: "Standard" }));
  } catch (e) {
    if (/** @type {{ name?: string }} */ (e).name === "ParameterAlreadyExists") { info(`${name}: present (kept)`); return "kept"; }
    throw new Error(`${name}: could not be stored in SSM (${/** @type {{ name?: string }} */ (e).name ?? "error"})`);
  }
  info(`${name}: generated and stored (SecureString; the value is not shown anywhere)`);
  return "created";
}

/**
 * Every generated secret, then the cache signing key pair: the private half SecureString (only the worker and the
 * warm-up function read it), the public half a plain String (not secret: the cache machine verifies with it; the stack
 * is built with it). Returns the public half. If the public half is missing, a new pair replaces both (the shared
 * cache then starts empty, which is harmless).
 */
export async function ensureGenerated(ssm, env = "prod") {
  for (const g of GENERATED) await ensureSecret(ssm, `${appPrefix(env)}/${g.name}`, g.make, `fenvix: ${g.what}. Generated by the deploy pipeline.`);
  const priv = `${cachePrefix(env)}/signing-key`;
  const pub = `${cachePrefix(env)}/signing-public-key`;
  if (await exists(ssm, pub) && await exists(ssm, priv)) {
    const r = await ssm.send(new GetParameterCommand({ Name: pub }));
    info(`${priv}: present (kept)`);
    return r.Parameter?.Value ?? "";
  }
  const pair = cacheKeyPair();
  await ssm.send(new PutParameterCommand({ Name: priv, Type: "SecureString", Value: pair.privatePem, Overwrite: true, Description: "fenvix: the private half of the cache signing key (signs per-job cache tokens). Generated by the deploy pipeline." }));
  await ssm.send(new PutParameterCommand({ Name: pub, Type: "String", Value: pair.publicDerBase64, Overwrite: true, Description: "fenvix: the public half of the cache signing key (not secret)." }));
  info(`${priv}: generated and stored (SecureString; the value is not shown anywhere); its public half in ${pub}`);
  return pair.publicDerBase64;
}
