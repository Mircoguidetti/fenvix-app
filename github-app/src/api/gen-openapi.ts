// Writes src/api/openapi.gen.ts from openapi/fenvix-api.yaml (the contract), so that the API's request validation and
// its route table work inside the Lambda bundle (no file read at run time). tests/api/unit.test.ts fails when the two
// differ: run `node src/api/gen-openapi.ts` (from github-app/) after changing the YAML.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

export const YAML_PATH = fileURLToPath(new URL("../../../openapi/fenvix-api.yaml", import.meta.url));
export const GEN_PATH = fileURLToPath(new URL("./openapi.gen.ts", import.meta.url));

/** The generated module's text for a YAML document. */
export function generated(yamlText: string): string {
  const json = JSON.stringify(parse(yamlText));
  return [
    "// GENERATED by src/api/gen-openapi.ts from openapi/fenvix-api.yaml. Do not edit: change the YAML and run",
    "// `node src/api/gen-openapi.ts` (github-app/). tests/api/unit.test.ts checks that this file is up to date.",
    `export const OPENAPI_JSON = ${JSON.stringify(json)};`,
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(GEN_PATH, generated(readFileSync(YAML_PATH, "utf8")));
  console.log(`wrote ${GEN_PATH}`);
}
