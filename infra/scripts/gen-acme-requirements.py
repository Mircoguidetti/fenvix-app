#!/usr/bin/env python3
"""Regenerates lib/acme-requirements.txt: certbot and its dependencies, pinned, with the SHA-256 of every wheel pip
could pick on the server (CPython 3.11, manylinux, x86_64 and aarch64). Hashes come from PyPI's JSON API. Run by a
person when updating certbot (README, "Updating certbot"); never at deploy or test time.

    python3 -I scripts/gen-acme-requirements.py certbot==5.8.0 acme==5.8.0 ... > lib/acme-requirements.txt

Then check the file resolves for both architectures (README shows the two `pip download --require-hashes` lines).
"""
import json, re, sys, urllib.request

PY = 11  # python3.11 on Amazon Linux 2023


def wanted(filename: str) -> bool:
    if not filename.endswith(".whl"):
        return False  # source archives would be built on the server: never
    _, _, tags = filename[:-4].partition("-")
    py, abi, plat = tags.rsplit("-", 3)[-3:]
    if plat == "any":
        return abi == "none" and any(p in ("py3", "py2.py3") or p.startswith("py3") for p in py.split("."))
    if not re.search(r"manylinux.*(x86_64|aarch64)", plat):
        return False
    if abi == f"cp3{PY}":
        return f"cp3{PY}" in py.split(".")
    if abi == "abi3":
        return any(int(t[3:]) <= PY for t in py.split(".") if t.startswith("cp3"))
    return False


out = []
for spec in sys.argv[1:]:
    name, version = spec.split("==")
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json") as r:
        files = json.load(r)["urls"]
    hashes = sorted({f["digests"]["sha256"] for f in files if wanted(f["filename"])})
    if not hashes:
        sys.exit(f"no usable wheel for {spec}")
    out.append(f"{name}=={version} \\\n" + " \\\n".join(f"    --hash=sha256:{h}" for h in hashes))
print("# Generated by scripts/gen-acme-requirements.py; do not edit by hand.")
print("\n".join(out))
