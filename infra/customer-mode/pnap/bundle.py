"""Builds the host bundle the App puts in each server's cloud-init user data: a deterministic tar.gz (sorted names,
fixed times and owners) of the host package, the guest image build, and the cache service, laid out as
/opt/fenvix-host. Writes github-app/src/pnap/host-bundle.generated.ts (base64 + SHA-256); the tests rebuild it and
fail when the checked-in copy is stale.

  python3 -I infra/customer-mode/pnap/bundle.py           # rewrite the generated file
  python3 -I infra/customer-mode/pnap/bundle.py --check   # exit 1 if it is out of date
"""

import base64
import gzip
import hashlib
import io
import os
import sys
import tarfile

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
OUT = os.path.join(REPO, "github-app", "src", "pnap", "host-bundle.generated.ts")
CACHE = os.path.join(REPO, "infra", "github-app", "lib", "cache")


def files():
    m = {}
    for d, prefix in ((os.path.join(HERE, "host"), ""), (os.path.join(HERE, "guest"), "guest/"), (os.path.join(HERE, "cache"), "cache/")):
        for root, dirs, names in os.walk(d):
            dirs[:] = sorted(x for x in dirs if x != "__pycache__")
            for n in sorted(names):
                if n.endswith(".pyc"):
                    continue
                p = os.path.join(root, n)
                m[prefix + os.path.relpath(p, d)] = p
    for n in ("cache_service.py", "fenvix_cache_auth.py"):
        m[f"cache/{n}"] = os.path.join(CACHE, n)
    return dict(sorted(m.items()))


def build() -> bytes:
    raw = io.BytesIO()
    with tarfile.open(fileobj=raw, mode="w", format=tarfile.PAX_FORMAT) as tar:
        for name, path in files().items():
            data = open(path, "rb").read()
            ti = tarfile.TarInfo(name)
            ti.size, ti.mtime, ti.uid, ti.gid, ti.uname, ti.gname = len(data), 0, 0, 0, "root", "root"
            ti.mode = 0o755 if os.access(path, os.X_OK) else 0o644
            tar.addfile(ti, io.BytesIO(data))
    out = io.BytesIO()
    with gzip.GzipFile(fileobj=out, mode="wb", mtime=0, compresslevel=9) as gz:
        gz.write(raw.getvalue())
    return out.getvalue()


def render(blob: bytes) -> str:
    b64 = base64.b64encode(blob).decode()
    lines = [b64[i:i + 120] for i in range(0, len(b64), 120)]
    return (
        "// GENERATED by infra/customer-mode/pnap/bundle.py: do not edit. The host bundle (/opt/fenvix-host) every\n"
        "// phoenixNAP server gets in its cloud-init user data; rebuilt and compared by the tests.\n"
        f'export const HOST_BUNDLE_SHA256 = "{hashlib.sha256(blob).hexdigest()}";\n'
        f"export const HOST_BUNDLE_FILES = {len(files())};\n"
        "export const HOST_BUNDLE_TGZ_BASE64 = [\n" + "".join(f'  "{l}",\n' for l in lines) + '].join("");\n'
    )


if __name__ == "__main__":
    text = render(build())
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT).read() == text
        print("host bundle up to date" if ok else "host bundle STALE: run python3 -I infra/customer-mode/pnap/bundle.py")
        sys.exit(0 if ok else 1)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write(text)
    print(f"wrote {OUT}: {len(files())} files, {len(build())} bytes gzipped")
